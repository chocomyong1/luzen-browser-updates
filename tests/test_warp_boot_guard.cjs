'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const read=p=>fs.readFileSync(path.join(__dirname,'..','AppSource',p),'utf8');
const warp=read('CloudflareWarpBoot.cs');
const main=read('MainForm.SplitView.cs');
const boot=read('MainForm.WindowsStartup.cs');
assert.match(warp,/DualSystemNetwork\.TryNormalizeProxy\(raw/);
assert.match(warp,/uri\.Host is not \("127\.0\.0\.1" or "localhost" or "::1"\)/);
assert.match(warp,/Environment\.SpecialFolder\.ProgramFiles/);
assert.match(warp,/Path\.Combine\(programFiles, "Cloudflare", "Cloudflare WARP", "warp-cli\.exe"\)/);
assert.match(warp,/UseShellExecute = false/);
assert.match(warp,/CreateNoWindow = true/);
assert.match(warp,/RunVendorCliAsync\(cli, "settings", token\)/);
assert.match(warp,/WarpProxy\\s\+on\\s\+port/);
assert.match(warp,/configuredPort != port/);
assert.match(warp,/RunVendorCliAsync\(cli, "status", token\)/);
assert.match(warp,/RunVendorCliAsync\(cli, "connect", token\)/);
assert(warp.indexOf('RunVendorCliAsync(cli, "settings"')<warp.indexOf('RunVendorCliAsync(cli, "connect"'));
assert(warp.indexOf('configuredPort != port')<warp.indexOf('RunVendorCliAsync(cli, "connect"'));
assert.doesNotMatch(warp,/RunVendorCliAsync\(cli, "mode"|Registry|ServiceController|powershell|cmd\.exe|Process\.Start\("[^"]+/i);
assert.match(boot,/_nextBootBWarpConnectUtc = DateTime\.UtcNow\.AddMinutes\(2\)/);
assert.match(boot,/_windowsBoot\.Enabled \|\| _bootCancelledByUser \|\| !_startTargets\.B/);
assert.match(main,/if \(silentStartup && _windowsBoot\.Enabled && !_bootCancelledByUser && _startTargets\.B\)/);
assert.match(main,/await TryBootBLocalProxyConnectAsync\(\)/);
assert(main.indexOf('await TryBootBLocalProxyConnectAsync()')<main.indexOf('await DualSystemNetwork.VerifyBRouteAsync()'));
assert.match(main,/_moduleA\.StartAutomationOnBoot\(\)/);
assert.match(main,/_moduleB\.StartAutomationOnBoot\(\)/);
assert.match(main,/else if \(!bReady && silentStartup && !_bootCancelledByUser\)\s*ScheduleBootBRetry\(\)/);
console.log('PASS B WARP local-proxy-only boot connection and A/B isolation guards');
